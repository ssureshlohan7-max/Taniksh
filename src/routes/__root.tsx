function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
        <meta name="monetag" content="20f0ba5615fb39813dc98588f5962683" />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  // Ad scripts mutate the page, so load them after hydration to avoid breaking React.
  const pathname = useRouterState({ select: (st) => st.location.pathname });
  useEffect(() => {
    // Ads only on content pages — not on sign-in, the builder, or user-made sites.
    if (/^\/(auth|forge|s\/)/.test(pathname)) return;
    if (!document.querySelector('script[src*="adsbygoogle.js"]')) {
      const g = document.createElement("script");
      g.async = true;
      g.crossOrigin = "anonymous";
      g.src =
        "https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-1612459588624758";
      document.head.appendChild(g);
    }
    for (const zone of ["11932530", "11932534"]) {
      if (document.querySelector(`script[data-zone="${zone}"]`)) continue;
      const s = document.createElement("script");
      s.dataset['zone'] = zone;
      s.src = "https://al5sm.com/tag.min.js";
      document.body.appendChild(s);
    }
  }, [pathname]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
